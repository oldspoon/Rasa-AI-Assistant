"""
Seed the attendance database: 15 students, each with a weekly Lecture and Practical,
plus rooms, parking charges and login accounts.
SQLite by default; Postgres when DATABASE_URL is set.

Run: python database/populate_db.py [--users-only | --parking-only]
Logins: username = first+last, password = last+first (lowercase).
"""

import random
import sys

# Windows console encoding fix.
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

try:
    from database import db  # package import
except ImportError:  # direct run
    import db

SQLITE_DDL = """
    CREATE TABLE IF NOT EXISTS attendance (
        id              INTEGER PRIMARY KEY AUTOINCREMENT,
        first_name      TEXT    NOT NULL,
        middle_name     TEXT    NOT NULL,
        last_name       TEXT    NOT NULL,
        campus          TEXT    NOT NULL CHECK(campus IN ('Craiglockhart', 'Sighthill', 'Merchiston')),
        session_type    TEXT    NOT NULL CHECK(session_type IN ('Lecture', 'Practical')),
        day_of_week     TEXT    NOT NULL CHECK(day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday')),
        time_range      TEXT    NOT NULL,
        activity        TEXT    NOT NULL CHECK(activity IN ('Fine Arts', 'Computing', 'Biology')),
        room            TEXT    NOT NULL
    )
"""

POSTGRES_DDL = """
    CREATE TABLE IF NOT EXISTS attendance (
        id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name      TEXT    NOT NULL,
        middle_name     TEXT    NOT NULL,
        last_name       TEXT    NOT NULL,
        campus          TEXT    NOT NULL CHECK(campus IN ('Craiglockhart', 'Sighthill', 'Merchiston')),
        session_type    TEXT    NOT NULL CHECK(session_type IN ('Lecture', 'Practical')),
        day_of_week     TEXT    NOT NULL CHECK(day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday')),
        time_range      TEXT    NOT NULL,
        activity        TEXT    NOT NULL CHECK(activity IN ('Fine Arts', 'Computing', 'Biology')),
        room            TEXT    NOT NULL
    )
"""

USERS_SQLITE_DDL = """
    CREATE TABLE IF NOT EXISTS users (
        id          INTEGER PRIMARY KEY AUTOINCREMENT,
        username    TEXT    NOT NULL UNIQUE,
        password    TEXT    NOT NULL,
        first_name  TEXT    NOT NULL,
        last_name   TEXT    NOT NULL
    )
"""

USERS_POSTGRES_DDL = """
    CREATE TABLE IF NOT EXISTS users (
        id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username    TEXT    NOT NULL UNIQUE,
        password    TEXT    NOT NULL,
        first_name  TEXT    NOT NULL,
        last_name   TEXT    NOT NULL
    )
"""

# (first, middle, last)
