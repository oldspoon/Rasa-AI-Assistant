def book_rows() -> list:
    """Book rows: (id, discipline, number, title, author)."""
    return [
        (BOOK_IDS[(discipline, number)], discipline, number, title, author)
        for discipline, titles in BOOKS.items()
        for number, (title, author) in enumerate(titles, start=1)
    ]


def loan_rows() -> list:
    """Loan rows: (book_id, first, last, campus, format, pickup_code, borrowed_on, due_on, returned_on)."""
    rows = []
    for index, number, kind, borrowed_on, due_on, returned_on, code in LOANS:
        first, _middle, last = STUDENTS[index]
        discipline = ACTIVITIES[index % len(ACTIVITIES)]
        rows.append(
            (BOOK_IDS[(discipline, number)], first, last, campus_for(index), kind, code,
             borrowed_on, due_on, returned_on)
        )
    return rows


def _seed_library(cursor) -> None:
    """Recreate the library tables: three libraries, fifteen books, a few loans."""
    cursor.execute("DROP TABLE IF EXISTS book_loans")
    cursor.execute("DROP TABLE IF EXISTS books")
    cursor.execute("DROP TABLE IF EXISTS libraries")
    for statement in library_ddl():
        cursor.execute(statement)

    placeholder = "%s" if db.is_postgres() else "?"

    def values(count: int) -> str:
        return ", ".join([placeholder] * count)

    cursor.executemany(
        f"INSERT INTO libraries (campus, name, location, room, opening_hours) VALUES ({values(5)})",
        LIBRARIES,
    )
    cursor.executemany(
        f"INSERT INTO books (id, discipline, number, title, author) VALUES ({values(5)})",
        book_rows(),
    )
    cursor.executemany(
        f"""
        INSERT INTO book_loans
            (book_id, first_name, last_name, campus, format, pickup_code,
             borrowed_on, due_on, returned_on)
        VALUES ({values(9)})
        """,
        loan_rows(),
    )


