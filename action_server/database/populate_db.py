"""
populate_db.py
Populates the attendance database with 15 students,
their campus assignments, sessions, rooms, and activities - plus one login
account per student (the `users` table).

Two modes, chosen automatically:
  * local (default)  -> (re)creates the SQLite file `attendance.db` here
  * DATABASE_URL set -> (re)creates and seeds that Postgres database instead
                        (e.g. the hosted Neon database)

Run:  python database/populate_db.py
      python database/populate_db.py --users-only   (login accounts only -
      does not touch the attendance table; handy for an existing database)

Login accounts follow one rule:
    username = first name + last name, run together, lowercase
    password = last name + first name, run together, lowercase
e.g. Alice Johnson -> alicejohnson / johnsonalice. Matching is
case-insensitive (and ignores spaces), so "Alice Johnson" works too.
"""

import random
import sys

# Keep the emoji/table output working on legacy Windows code pages.
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

try:
    from database import db          # imported as part of the package
except ImportError:                  # run directly: python database/populate_db.py
    import db

SQLITE_DDL = """
    CREATE TABLE IF NOT EXISTS attendance (
        id              INTEGER PRIMARY KEY AUTOINCREMENT,
        first_name      TEXT    NOT NULL,
        middle_name     TEXT    NOT NULL,
        last_name       TEXT    NOT NULL,
        campus          TEXT    NOT NULL CHECK(campus IN ('Craiglockhart', 'Sighthill', 'Merchiston')),
        session_type    TEXT    NOT NULL CHECK(session_type IN ('Lecture', 'Practical')),
        day_of_week     TEXT    NOT NULL CHECK(day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday')),
        time_range      TEXT    NOT NULL,
        activity        TEXT    NOT NULL CHECK(activity IN ('Fine Arts', 'Computing', 'Biology')),
        room            TEXT    NOT NULL
    )
"""

POSTGRES_DDL = """
    CREATE TABLE IF NOT EXISTS attendance (
        id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name      TEXT    NOT NULL,
        middle_name     TEXT    NOT NULL,
        last_name       TEXT    NOT NULL,
        campus          TEXT    NOT NULL CHECK(campus IN ('Craiglockhart', 'Sighthill', 'Merchiston')),
        session_type    TEXT    NOT NULL CHECK(session_type IN ('Lecture', 'Practical')),
        day_of_week     TEXT    NOT NULL CHECK(day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday')),
        time_range      TEXT    NOT NULL,
        activity        TEXT    NOT NULL CHECK(activity IN ('Fine Arts', 'Computing', 'Biology')),
        room            TEXT    NOT NULL
    )
"""

USERS_SQLITE_DDL = """
    CREATE TABLE IF NOT EXISTS users (
        id          INTEGER PRIMARY KEY AUTOINCREMENT,
        username    TEXT    NOT NULL UNIQUE,
        password    TEXT    NOT NULL,
        first_name  TEXT    NOT NULL,
        last_name   TEXT    NOT NULL
    )
"""

USERS_POSTGRES_DDL = """
    CREATE TABLE IF NOT EXISTS users (
        id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username    TEXT    NOT NULL UNIQUE,
        password    TEXT    NOT NULL,
        first_name  TEXT    NOT NULL,
        last_name   TEXT    NOT NULL
    )
"""

# 15 students with first, middle, last names
STUDENTS = [
    ("Alice",   "Marie",    "Johnson"),
    ("Bob",     "James",    "Smith"),
    ("Carol",   "Anne",     "Williams"),
    ("David",   "Lee",      "Brown"),
    ("Emma",    "Grace",    "Jones"),
    ("Frank",   "Thomas",   "Garcia"),
    ("Grace",   "Louise",   "Miller"),
    ("Henry",   "Charles",  "Davis"),
    ("Isabella","Rose",     "Wilson"),
    ("Jack",    "Edward",   "Moore"),
    ("Katie",   "Lynn",     "Taylor"),
    ("Liam",    "Patrick",  "Anderson"),
    ("Mia",     "Claire",   "Thomas"),
    ("Noah",    "William",  "Jackson"),
    ("Olivia",  "Faith",    "White"),
]


def derive_credentials(first_name: str, last_name: str) -> tuple:
    """(username, password) for one student: first+last / last+first, lowercase."""
    username = f"{first_name}{last_name}".lower()
    password = f"{last_name}{first_name}".lower()
    return username, password


def user_rows() -> list:
    """The `users` rows for the seeded cohort: (username, password, first, last)."""
    rows = []
    for first, _middle, last in STUDENTS:
        username, password = derive_credentials(first, last)
        rows.append((username, password, first, last))
    return rows


def _seed_users(cursor) -> None:
    """(Re)create the `users` table and insert one login per student."""
    cursor.execute("DROP TABLE IF EXISTS users")
    cursor.execute(USERS_POSTGRES_DDL if db.is_postgres() else USERS_SQLITE_DDL)

    placeholder = "%s" if db.is_postgres() else "?"
    values = ", ".join([placeholder] * 4)
    cursor.executemany(
        f"""
        INSERT INTO users (username, password, first_name, last_name)
        VALUES ({values})
        """,
        user_rows(),
    )


def _print_users() -> None:
    print("\n🔐  Login accounts (username / password):\n")
    print(f"{'Username':<20} {'Password':<20} {'Student'}")
    print("-" * 60)
    for username, password, first, last in user_rows():
        print(f"{username:<20} {password:<20} {first} {last}")
    print()


def create_users_only():
    """(Re)create just the `users` table - leaves `attendance` untouched."""
    conn = db.connect()
    try:
        cursor = conn.cursor()
        _seed_users(cursor)
        conn.commit()
    finally:
        conn.close()

    print(f"✅  Login accounts created in: {db.describe_backend()}")
    print(f"✅  {len(STUDENTS)} users inserted.")
    _print_users()


def create_database():
    conn = db.connect()
    try:
        cursor = conn.cursor()

        cursor.execute("DROP TABLE IF EXISTS attendance")
        cursor.execute(POSTGRES_DDL if db.is_postgres() else SQLITE_DDL)

        campuses      = ["Craiglockhart", "Sighthill", "Merchiston"]
        session_types = ["Lecture", "Practical"]
        days          = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]
        activities    = ["Fine Arts", "Computing", "Biology"]

        # Valid 2-hour time slots within 10:00–17:00
        time_slots = [
            "10:00-12:00",
            "11:00-13:00",
            "12:00-14:00",
            "13:00-15:00",
            "14:00-16:00",
            "15:00-17:00",
        ]

        def random_room():
            letter = random.choice("ABCDEF")
            number = random.randint(0, 99)
            return f"{letter}{number:02d}"

        random.seed(42)

        rows = []
        for i, (first, middle, last) in enumerate(STUDENTS):
            campus       = campuses[i % len(campuses)]
            session_type = session_types[i % len(session_types)]
            day          = days[i % len(days)]
            time_range   = time_slots[i % len(time_slots)]
            activity     = activities[i % len(activities)]
            room         = random_room()
            rows.append((first, middle, last, campus, session_type, day, time_range, activity, room))

        placeholder = "%s" if db.is_postgres() else "?"
        values = ", ".join([placeholder] * 9)
        cursor.executemany(
            f"""
            INSERT INTO attendance
                (first_name, middle_name, last_name, campus, session_type,
                 day_of_week, time_range, activity, room)
            VALUES ({values})
            """,
            rows,
        )

        # One login account per student (same first/last names).
        _seed_users(cursor)

        conn.commit()

        cursor.execute("SELECT * FROM attendance ORDER BY id")
        records = [dict(r) for r in cursor.fetchall()]
    finally:
        conn.close()

    print(f"✅  Database created at: {db.describe_backend()}")
    print(f"✅  {len(records)} student records inserted.")
    print(f"✅  {len(STUDENTS)} login accounts inserted.\n")
    print(f"{'ID':<4} {'First':<10} {'Middle':<10} {'Last':<12} {'Campus':<16} "
          f"{'Type':<10} {'Day':<12} {'Time':<14} {'Activity':<12} {'Room'}")
    print("-" * 110)
    for r in records:
        print(f"{r['id']:<4} {r['first_name']:<10} {r['middle_name']:<10} "
              f"{r['last_name']:<12} {r['campus']:<16} {r['session_type']:<10} "
              f"{r['day_of_week']:<12} {r['time_range']:<14} "
              f"{r['activity']:<12} {r['room']}")
    _print_users()


if __name__ == "__main__":
    if "--users-only" in sys.argv[1:]:
        create_users_only()
    else:
        create_database()
